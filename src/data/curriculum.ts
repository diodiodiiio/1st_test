export const getAllLessons = () =>
  CURRICULUM.flatMap((unit) => unit.lessons.map((lesson) => ({ ...lesson, unitId: unit.id })));

export const getLessonById = (lessonId: string) =>
  getAllLessons().find((l) => l.id === lessonId);

export const getUnitById = (unitId: string) =>
  CURRICULUM.find((u) => u.id === unitId);

export const isUnitUnlocked = (unitId: string, completedLessons: string[]): boolean => {
  const unitIndex = CURRICULUM.findIndex((u) => u.id === unitId);
  if (unitIndex === 0) return true;
  const prevUnit = CURRICULUM[unitIndex - 1];
  return prevUnit.lessons.every((l) => completedLessons.includes(l.id));
};
